"""### List Mutability Basics
While strings are immutable, lists are *mutable*, meaning we can
change (or mutate) lists.

It is important that you understand this well.

#### Lists are Mutable
For example, for a list L, we *can* change the value of L[i].
"""

L = [ 2, 4, 6, 8 ]
L[0] = 42
print(L)

"""#### List Aliases

Before we proceed, we must briefly cover how list aliases work.

As we already saw, variables are *aliases* if they are set to the same Python object.  Two variables set to the same list are *list aliases*.

This is how we create a list alias:
<pre>
    L = [ 1, 2 ]
    M = L  # Now L and M are aliases (set to the same list)
</pre>

If we mutate a list, all the aliases reflect the change.
"""

L = [ 1, 2 ]
M = L      # Now L and M are aliases
L[0] = 42  # This mutates L
print(L)
print(M)   # Surprised?

"""We use `is` to test if two values are aliases."""

L = [ 1, 2 ]
M = L
print(L == M)
print(L is M)

"""Two lists can be equal but not aliases."""

L = [ 1, 2 ]
M = [ 1, 2 ] # This is NOT an alias.  It is a new list.
print(L == M)
print(L is M)

"""We now can return to discussing list mutability.

#### Testing for Mutation
As we discuss below, some operators and methods mutate a list, and others do not.

For example (again discussed below), the following two lines both add a value
to the list L.  The first line mutates the list, and the second line does not.
<pre>
    L += [ 42 ]    # this mutates L

    L = L + [ 42 ] # this does not mutate L
</pre>

We need an easy way to test if a list was mutated.  In fact, here are two ways.

##### Using id()

Every object in Python has a unique id associated with it.

We use `id(value)` to get the id of a value.

If a list changes, but keeps the same id, then it was mutated.

If a list changes, but has a new id, then it was not mutated.
"""

# Using id() to confirm L was mutated:

L = [ 1, 2 ]
print(L)
print(id(L))

L += [ 3 ]
print(L)
print(id(L)) # did not change, so L was mutated!

# Using id() to confirm L was NOT mutated:

L = [ 1, 2 ]
print(L)
print(id(L))

L = L + [ 3 ]
print(L)
print(id(L)) # changed, so L was NOT mutated!

"""##### Using Aliases
We can test for mutation of L by first creating an alias M.

Then, if L changes:

  * if L was mutated, M will reflect the change.
  
  * if L was not mutated, M will not reflect the change.
"""

# Using an alias to confirm L was mutated:

L = [ 1, 2 ]
M = L
print(L, M)

L += [ 3 ]
print(L, M) # M changed, so L was mutated

# Using an alias to confirm L was NOT mutated:

L = [ 1, 2 ]
M = L
print(L, M)

L = L + [ 3 ]
print(L, M) # M did NOT change, so L was NOT mutated

