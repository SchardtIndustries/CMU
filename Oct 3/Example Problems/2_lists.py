"""## List Methods

### Non-Mutating Methods

#### L.index
`L.index(v)` returns the index of the first occurrence of v in L.
"""

L = [ 2, 3, 5, 7 ]
print(L.index(5))

"""If v is not in L, L.index(v) crashes."""

L = [ 2, 3, 5, 7 ]
print(L.index(42)) # crashes (42 is not in the list)

"""#### No L.find(v)
Regarding L.find(v):

  * We saw that a string s has two similar methods, s.index(t) and s.find(t).

    * s.find(t) is preferred, since it does not crash if t is not in s.

  * We just saw that lists have L.index(v), which works similarly to s.index(t).

  * Unfortunately, there is no L.find(v).  So for lists, we have to use L.index(v).
  
However:

  * We can write our own find function for lists.
"""

# Our own find(L, v) function for lists, since L.find(v) does not exist.

def find(L, v):
    for i in range(len(L)):
        if L[i] == v:
            return i
    return -1

L = [ 7, 11, 13, 17 ]
print(find(L, 13))
print(find(L, 15)) # works

print(L.index(13))
print(L.index(15)) # crashes

