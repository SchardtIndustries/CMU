"""## Looping Over Lists
We loop over lists in the same way that we loop over strings.

### Looping over Values
We use `for v in s` to loop the variable v over each value
in the list L.
"""

L = [ 2, 3.14, 'yes!' ]
for v in L:
    print(f'The next value is: {v}')

"""### Looping over Indexes
We use `for i in range(len(L))` to loop the variable i over each valid *index*
of the list L.

Then we use `L[i]` to access the ith value in L.
"""

L = [ 2, 3.14, 'yes!' ]
for i in range(len(L)):
    v = L[i]
    print(f'Value {i} is {v}')

"""### Reverse Looping over Indexes
We use `for i in range(len(L)-1, -1, -1)` to loop the variable i
*in reverse order* over each valid index of L.
"""

L = [ 2, 3.14, 'yes!' ]
for i in range(len(L)-1, -1, -1):
    v = L[i]
    print(f'Value {i} is {v}')

"""## List Comprehensions
A *list comprehension* compactly and efficiently creates a list by evaluating
an expression for each value in a sequence.

The general form (or *syntax*) of a list comprehension is:
<pre>
    [expression for item in sequence]
</pre>
Here, *item* is the loop variable, and *expression* uses *item*
to compute the values in the list.

For example:
"""

L = [ x**2 for x in range(10) ] # list of the first 10 squares
print(L)

"""We can add a *condition* like so:
<pre>
    [expression for item in sequence if condition]
</pre>

For example:
"""

L = [ x**2 for x in range(10) if x % 2 == 0 ] # just the even squares
print(L)

"""## Mutability and Functions Using Lists

### Parameters are Aliases
Parameters are aliases, so if a parameter is a list, and you change (mutate) that
list, you just changed the caller's list (so be sure that is what you meant to do!).
"""

def f(M):
    print(f'id(M) = {id(M)}') # this is an alias to L!

L = [1, 2]
print(f'id(L) = {id(L)}')
f(L)

"""### Avoid Mutating Parameters
Since parameters are aliases, you should *avoid mutating parameters* unless
that is the well-understood purpose of your function.

For example, never do this:
"""

# This code shows how you should never write a function!
# This unexpectedly mutates (changes) the caller's list.
# This is *extremely* undesirable.

def endsInEven(L):
    if len(L) == 0:
        return False
    else:
        return L.pop() % 2 == 0 # This mutates the caller's list!

L = [ 1, 2, 3 ]
print(L)             # to start...
print(endsInEven(L)) # seems to work
print(L)             # oh no!

"""Instead, find a way to write your function without mutating.
In this case, like so:
"""

# This code fixes the problem from above, and does not mutate its parameter.

def endsInEven(L):
    if len(L) == 0:
        return False
    else:
        return L[-1] % 2 == 0 # Better!

L = [ 1, 2, 3 ]
print(L)             # to start...
print(endsInEven(L)) # seems to work
print(L)             # whew!

"""### Copying Breaks Aliases
Continuing with the previous example, if you really cannot find a better way,
you can always just copy a list.

Once you copy a list, it is not longer an alias, so changes to it do not
affect the original list.
"""

# This code is not optimal (the previous example is preferable),
# but if you really can't do anything else, you can usually
# avoid mutating simply by copying the list.

import copy

def endsInEven(L):
    L = copy.copy(L) # <-- This breaks the alias
    if len(L) == 0:
        return False
    else:
        return L.pop() % 2 == 0 # This no longer mutates the caller's list!

L = [ 1, 2, 3 ]
print(L)             # to start...
print(endsInEven(L)) # seems to work
print(L)             # whew!

"""Note that the solution that uses copy is very wasteful -- it creates an entire
new copy of the list just to pop the last element!

It is much better to just index into the last element, as we saw above.

### Writing Mutating Functions
In general, your functions should not mutate parameters.  However, there are times
when you actually *intend* to do this.  In that case:

  * Give the function a name that makes this as clear as possible.
  
  * Document that the function is mutating, at least in a clear comment.
  
  * If possible, have the function return None.  This is a clear sign
    that a function is mutating.
"""

# This function is mutating! It adds 10 to every value in L.
# This function returns None (by default).
def addTenToEveryValue(L):
    for i in range(len(L)):
        L[i] += 10

L = [ 1, 2, 3 ]
print(L)
print(addTenToEveryValue(L)) # None (the function returns None, as it should)
print(L)

"""## Anti-Pattern: Modifying while Looping
You should avoid modifying a list that you are looping over.
This often causes Python to crash.
"""

# This code does not work!
L = [ 2, 8, 6, 4]
for i in range(len(L)):
    if L[i] > 5:
        L.pop(i) # This modifies the list L inside the loop (and crashes!)
print(L)

"""The problem is that range() is called only once at the start of the loop.
It does not change when the list gets smaller.

A fix for this is to use a while loop without calling range() at all.
"""

# This code works!
L = [ 2, 8, 6, 4]
i = 0
while i < len(L):
    if L[i] > 5:
        L.pop(i)
    else:
        i += 1
print(L) # [2, 4]

"""Note that sometimes we *can* use a for loop, by looping in reverse order.
If you opt for this approach, be sure you thoroughly understand this
(so you know when this approach will not work)!
"""

# This code also works!
L = [ 2, 8, 6, 4]
for i in range(len(L)-1, -1, -1):
    if L[i] > 5:
        L.pop(i)
print(L)

"""Here is a more useful example.  Note that Python does not include a
built-in function that removes all the occurrences of a value from a list.
So this is handy!
"""

# This function modifies L by removing every occurrence of v.
def removeAll(L, v):
    for i in range(len(L)-1, -1, -1):
        if L[i] == v:
            L.pop(i)

L = [ 1, 2, 3, 1, 2, 3, 1, 2, 3 ]
print(L)
print(removeAll(L, 2)) # None (removeAll is mutating and correctly returns None)
print(L) # works!