"""## String Methods

### Character Type Methods
These test if a string s contains only characters of a certain type.

Note that these have some subtleties we will cover in the Additional Topics.

#### s.isalpha
`s.isalpha()` tests if s contains only letters (alphabetics)
"""

print('AbCd'.isalpha())
print('Ab34'.isalpha())

"""#### s.isdigit
`s.isdigit()` tests if s contains only digits.
"""

print('1234'.isdigit())
print('123C'.isdigit())

"""#### s.isalnum
`s.isalnum()` tests if s contains only letters (alphabetics) or digits (numerics).
"""

print('Ab34'.isalnum())
print('Ab??'.isalnum())

"""####  s.islower
`s.islower()` tests if s contains letters and they are all lowercase.
"""

print('abcd'.islower())
print('abCD'.islower())
print('ab12'.islower()) # surprised?
print('1234'.islower()) # surprised?

"""#### s.isupper
`s.isupper()` tests if s contains letters and they are all uppercase.
"""

print('ABCD'.isupper())
print('ABcd'.isupper())
print('AB12'.isupper())
print('1234'.isupper())

"""#### s.isspace
`s.isspace()` tests if s contains only *whitespace* (spaces, tabs, or newlines)
"""

print('  \n'.isspace())
print('   x'.isspace())

"""### String Editing Methods
These methods make edits on a string, returning a new string.

#### s.lower
`s.lower()` converts the letters in s to lowercase, leaving non-letters unchanged.
"""

print('ABC def 123 !!!'.lower())

"""#### s.upper
`s.upper()` converts the letters in s to uppercase, leaving non-letters unchanged.
"""

print('ABC def 123 !!!'.upper())

"""#### s.replace
`s.replace(u, v)` replaces all the occurrences of the string u in s with v,
where u and v are both strings.
"""

print('This is a good example. A really good example!'.replace('good', 'great'))

"""`s.replace(u, v, count)` replaces only the first `count` occurrences of u."""

print('abc abc abc'.replace('a', 'x'))    # replace every a with x
print('abc abc abc'.replace('a', 'x', 1)) # replace just the first a
print('abc abc abc'.replace('a', 'x', 2)) # replace just the first two a's

"""#### s.strip
`s.strip()` removes any leading or trailing whitespace in s.
"""

print(repr('     This is a test!     '.strip()))

"""Leading or trailing newlines are also stripped."""

print(repr('''

Hello!

'''.strip()))

"""Note that `s.strip()` does not remove any internal whitespace in s."""

print(repr('     s   u   r   p   r   i   s   e   d   ?      '.strip()))

"""### Substring Search Methods
These search a string for occurrences of a substring.

#### s.count
`s.count(t)` returns the number of times t occurs in s.
"""

print('abcd abc ab a'.count('bc'))

"""#### s.startswith
`s.startswith(t)` tests if s starts with t.
"""

print('cheerful morning, cheerful day'.startswith('cheer'))
print('cheerful morning, cheerful day'.startswith('morning'))

"""#### s.endswith
`s.endswith(t)` tests if s ends with t.
"""

print('Happy day, sound sleep'.endswith('sleep'))
print('Happy day, sound sleep'.endswith('sound'))

"""#### s.find
`s.find(t)` returns the index where the first t occurs in s,
or -1 if s does not contain t.
"""

print('I am happy if you are happy'.find('happy'))
print('I am happy if you are happy'.find('sad'))

"""`s.find(t, start)` works the same as `s.find(t)` but it
starts checking from the given index.
"""

print('I am happy if you are happy'.find('happy'))
print('I am happy if you are happy'.find('happy', 5)) # surprised?
print('I am happy if you are happy'.find('happy', 6))
print('I am happy if you are happy'.find('sad', 6))

"""#### s.index
`s.index(t)` works the same as `s.find(t)`, only it raises an exception
(crashes) if t is not in s.
"""

# This works just like find:
print('I am happy if you are happy'.index('happy'))

# But this crashes:
print('I am happy if you are happy'.index('sad')) # crash: substring not found

"""#### s.rfind
`s.rfind(t)` works the same as `s.find(t)` but it searches from the *right*.
So it finds the *last* occurrence of t in s.
"""

print('I am happy if you are happy'.rfind('happy'))

"""### Splitting Methods
These methods split a string up into parts that we can loop over.

Since these return lists, we will cover these methods after lists.

## String Literals
A string value in quotes is called a *string literal*.

#### Kinds of Quotes
We can use several different kinds of quotes in strings:

  * single quotes ('like this')
  
  * double quotes ("like this")
  
  * triple single quotes ('''like this''')
  
  * triple double quotes ('''like this''')
"""

print('This uses single quotes.')
print("This uses double quotes.")
print('''This uses triple single quotes.''')
print("""This uses triple double quotes.""")

"""Both types of triple quotes allow newlines in the string."""

print('''
This is
a multiline string.''')

print("""
And this is
another multiline string.""")

"""Python crashes if we put single quotes in a single-quoted string."""

# Error: placing a single-quote inside a single-quoted string:
#print('This can't work!')

"""We can fix this by using double-quotes or by escaping the single-quote with
a backslash (`\`).
"""

print("This doesn't crash!")
print('And this also doesn\'t crash!')

"""### Escape Sequences
We use `\` (backslash) to include special characters in strings.

  * These are called *escape sequences*.
  
  * While we type them with two characters, escape sequences count as just a single character
    in the string.

#### \n
`\n` is a newline character.
"""

print('abc\ndef')

"""Again, escape sequences count as just one character."""

print(len('abc\ndef'))

"""#### \t
`\t` is a tab character.
"""

print('abc\tdef')
print('ab\tcdef')

"""#### \\'
`\'` is the single-quote character.
"""

print('You don\'t have to use double-quotes here!')

"""#### \\"
`\"` is the double-quote character.
"""

print("And I quote: \"You can do this in double-quotes!\"  Amazing!")

"""#### \\\\
`\\` is the backslash character.
"""

print('This is a backslash: \\')

