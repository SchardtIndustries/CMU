"""## Strings and Aliases

Values in Python are also called *objects*.

Variables are *aliases* if they are set to the same Python object.

Since strings are immutable, changing a string does not change aliases.
"""

s = 'abc'
t = s      # now s and t are aliases, both set to the same string
s += 'def' # we just changed s
print(s)
print(t)   # surprised?