"""### ord
Every character has a unique Unicode value assigned to it.

We can use `ord(s)` to convert a single-character string into its
Unicode value.
"""

print(ord('A')) # uppercase A is 65
print(ord('a')) # lowercase a is 97
print(ord('0')) # the character '0' (not the int value 0) is 48
print(ord('!')) # exclamation mark is 33
print(ord(' ')) # space is 32

"""The uppercase letters are in the same order alphabetically as in Unicode."""

import string
for letter in string.ascii_uppercase:
    print(f'Unicode for {letter} is {ord(letter)}')

"""The lowercase letters are also in the same order alphabetically as in Unicode."""

import string
for letter in string.ascii_lowercase:
    print(f'Unicode for {letter} is {ord(letter)}')

"""However, all the lowercase letters are after all of the uppercase letters."""

print(ord('a'), ord('Z'))
print(ord('a') > ord('Z')) # surprised?

"""Python uses Unicode values when comparing letters. So all lowercase letters
are greater than all uppercase letters.
"""

print('a' > 'Z') # surprised?

"""### chr
We use `chr(n)` to convert the Unicode value n back into a string of length 1
of the corresponding character.
"""

print(ord('A')) # Unicode for A is 65
print(chr(65))  # So chr(65) returns the string 'A'

"""We see that chr and ord are *inverse functions* -- they undo what the other does.  So:

  * chr(ord(s)) == s, and
  
  * ord(chr(n)) == n
"""

print(ord(chr(63)) == 63)
print(ord(chr(192)) == 192)

print(chr(ord('!')) == '!')
print(chr(ord('+')) == '+')

"""### repr
We use `repr(s)` to get the Python-readable string representation of a value.

This is especially useful when debugging to help us see whitespace
(spaces, tabs, newlines) at the end of a string.
"""

s = 'This has extra spaces at the end.  '
print(s)       # not obvious here
print(repr(s)) # but it is obvious here!

"""`repr` also can be useful for debugging multiline strings
because it displays newline characters as `\n`.
"""

s = '''a
b'''
print(repr(s))

