import string

def mostFrequentLetters(text):
    text = text.upper()
    bestCount = bestLetters = None
    for letter in string.ascii_uppercase:
        count = text.count(letter)
        if (count > 0) and ((bestCount == None) or (count > bestCount)):
            bestCount = count
            bestLetters = letter
        elif count == bestCount:
            bestLetters += letter
    return bestLetters

