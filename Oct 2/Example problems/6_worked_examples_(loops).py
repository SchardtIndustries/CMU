import string

# We provide two sample solutions here. This solution checks that every
# letter in the alphabet appears the same number of times in s1 and s2

def areAnagrams(s1, s2):
    s1 = s1.lower()
    s2 = s2.lower()
    for letter in string.ascii_lowercase:
        if s1.count(letter) != s2.count(letter):
            return False
    return True

