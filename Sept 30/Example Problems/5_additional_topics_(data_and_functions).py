"""### Functions as Arguments
We can write functions that take other functions as arguments.
"""

def callTwice(f, x):
    return f(f(x))

def timesTen(x):
    return 10*x

def divideByTen(x):
    return x//10

print(callTwice(timesTen, 456))
print(callTwice(divideByTen, 456))

"""### Functions that Return Functions
Functions can even return functions:
"""

def makeCallTwiceFunction(f):
    def newFunction(x):
        return f(f(x))
    return newFunction

def timesTen(x):
    return 10 * x

def divideByTen(x):
    return x // 10

timesHundred = makeCallTwiceFunction(timesTen)
divideByHundred = makeCallTwiceFunction(divideByTen)

print(timesHundred(456))
print(divideByHundred(456))

"""### Lambda Functions
Lambda functions are also called `anonymous functions`.<br>
Lambda functions are expressions, and can be assigned to variables.<br>
Lambda functions are limited in Python, and can only return a single expression.
"""

def callTwice(f, x):
    return f(f(x))

f = lambda x: 10 * x

print(f(456))
print(callTwice(f, 456))

"""We can use a lambda function without ever assigning it to a variable:"""

def callTwice(f, x):
    return f(f(x))

print(callTwice(lambda x: x * 10, 456))

"""## More on Globals
While globals are discouraged, they are used sometimes in practice, so
it's good for you to know a bit more about them.

### Assignment and Locals
Assigning a value to a variable in a function makes that variable local. <br>
If there is a global variable of the same name, we say that the local
variable *hides* the global variable.
"""

delta = 42 # global

def f(x):
    delta = 5 # hides the global, so this is a local variable
    return x + delta

def g(x):
    return x + delta

print(f(1))
print(g(1))
print(delta)

"""### The global Declaration
We use `global` to declare a variable is global.  Compare this code
to the code above:
"""

delta = 42 # global

def f(x):
    global delta # this makes delta global
    delta = 5 # does not hides the global anymore
    return x + delta

def g(x):
    return x + delta

print(f(1))
print(g(1))
print(delta)

"""### locals() and globals()
These functions return the local and global variables currently in scope. <br>
Printing locals can be useful when debugging.
"""

delta = 42

def f(x):
    print(locals())
    print(globals()) # this prints a lot!
    return x + delta

print(f(1))

"""We can use `globals()` to access a hidden global variable:"""

delta = 42

def f(x):
    delta = 5 # hides the global
    print(f'local value of delta: {delta}')
    print(f'global value of delta: {globals()["delta"]}')
    return x + delta

print(f(1))

"""## docstrings
We can provide *documentation* for a function by adding a *docstring*
after the `def` line. Then `help` works with the function.
"""

def absoluteDifference(x, y):
    """
    Returns the absolute difference between x and y.  That is, |x - y|.

    Args:
        x (int): The first number.
        y (int): The second number.

    Returns:
        int: The absolute difference |x - y|.
    """
    return abs(x - y)

print(absoluteDifference(3, 5))
help(absoluteDifference)