"""### pow and math.pow
We use `**` to exponentiate, but `pow` and `math.pow` also do this. <br>
They work subtly differently, however.<br>
For example, `math.pow` returns floats, and does not work over complex numbers.<br>
We suggest you stick with `**` to exponentiate.
"""

import math
print(2**5)
print(pow(2, 5))
print(math.pow(2, 5)) # note this is a float

# (1 + 2j) is a complex number
print((1 + 2j) ** 3)       # works
print(pow(1 + 2j, 3))      # works
print(math.pow(1 + 2j, 3)) # fails

