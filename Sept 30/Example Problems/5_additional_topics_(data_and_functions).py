"""If you truly require rounding up in the more

---

traditional way,
you can use this `roundHalfUp` function we provdide for you here:
"""

import decimal

def roundHalfUp(d):
    # Round to nearest with ties going away from zero.
    rounding = decimal.ROUND_HALF_UP
    return int(decimal.Decimal(d).to_integral_value(rounding=rounding))

print(roundHalfUp(1.5))
print(roundHalfUp(2.5)) # works as expected

print(roundHalfUp(-2.5)) # ditto
print(roundHalfUp(-1.5))

