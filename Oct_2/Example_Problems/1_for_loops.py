"""Remember that range(n) always excludes n itself."""

# Working version:
def sumToN(n):
    total = 0
    for x in range(n+1): # <-- we use (n+1) so n is in the range!
        total += x
    return total

print(sumToN(5)) # better!

"""Aside: the `sum` function works on ranges, so we did not actually
need to use a loop here:
"""

# Alternate version without loops:
def sumToN(n):
    return sum(range(n+1))

print(sumToN(5))

"""Actually, we could also use the well-known formula for the sum of the integers up to n
(Gauss's Formula).
"""

# Another alternate version using Gauss's Formula
def sumToN(n):
    return n * (n+1) // 2  # use // to get an integer result

print(sumToN(5))

