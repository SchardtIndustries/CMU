# This time with numbered lines:
def printTenSumProducts(maxValue):
    lineNumber = 1
    for x in range(1, maxValue + 1):
        for y in range(x, maxValue + 1):
            if x * y == 10 * (x + y):
                print(f'Pair #{lineNumber}: ', end='')
